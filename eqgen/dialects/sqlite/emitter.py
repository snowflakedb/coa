"""How SQLite differs from the portable default.

Pinned amalgamation ≥3.39 has native ``RIGHT`` / ``FULL OUTER JOIN``; we emit them as-is
(``visit_join_query``). ``QUALIFY`` becomes a subquery + ``WHERE``.
Type spelling uses SQLite affinity names.

**Type affinity.** SQLite assigns affinity to *table* columns from their declared type, but
expressions (window functions, arithmetic, compound ``UNION ALL`` result columns) often have
*no* affinity. Views expose expression affinity, not the base table's
(https://www.sqlite.org/datatype3.html §3.2–3.3.1). Equivalence rewrites that turn a base
table into views/windows/unions therefore change how comparisons coerce — e.g.
``1462169534 > c_txt`` can match a real ``TEXT`` column and miss the same value through a
view. Wrapping every projected column in ``CAST(... AS <declared type>)`` restores the
declared affinity on every ``CREATE … AS`` boundary so base and equivalent agree.
"""

